import pg from "pg";
import { localIso } from "./files.js";

// Each entry moves the schema up one version (table schema_version). Never edit an entry that has already run on the site:
// add a new one instead. seq keeps the order rows were added in, as rowid did in SQLite.
// JSON stays in text columns: the code compares product JSON as text, and jsonb would reorder its keys.
const MIGRATIONS = [
  `CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
   CREATE TABLE settings (seq BIGINT GENERATED BY DEFAULT AS IDENTITY, key TEXT PRIMARY KEY, value TEXT NOT NULL);
   CREATE TABLE products (seq BIGINT GENERATED BY DEFAULT AS IDENTITY, id TEXT PRIMARY KEY, position INTEGER NOT NULL, data TEXT NOT NULL);
   CREATE TABLE orders (
     id TEXT PRIMARY KEY,
     number INTEGER NOT NULL UNIQUE,
     key TEXT UNIQUE,
     created_at TEXT NOT NULL,
     status TEXT NOT NULL,
     name TEXT NOT NULL,
     phone TEXT NOT NULL,
     items TEXT NOT NULL,
     totals TEXT NOT NULL,
     extra TEXT
   );
   CREATE TABLE deleted_orders (key TEXT PRIMARY KEY, number INTEGER NOT NULL, deleted_at TEXT NOT NULL);
   CREATE TABLE counters (name TEXT PRIMARY KEY, value INTEGER NOT NULL);
   CREATE TABLE clients (
     seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
     id TEXT PRIMARY KEY,
     phone TEXT NOT NULL UNIQUE,
     name TEXT NOT NULL,
     created_at TEXT NOT NULL,
     last_order_at TEXT NOT NULL,
     hidden BOOLEAN NOT NULL DEFAULT FALSE,
     extra TEXT
   );
   CREATE TABLE chat_files (
     seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
     id TEXT PRIMARY KEY,
     name TEXT NOT NULL,
     type TEXT NOT NULL,
     size BIGINT NOT NULL,
     session TEXT NOT NULL,
     text TEXT NOT NULL,
     created_at TEXT NOT NULL,
     time BIGINT NOT NULL
   );
   -- Pieces on hand per product and size ("" for a product without sizes). A product without rows is not counted.
   -- Kept apart from the product JSON so orders taking stock never look like an edit from another admin window.
   CREATE TABLE stock (
     seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
     product_id TEXT NOT NULL,
     size TEXT NOT NULL,
     qty INTEGER NOT NULL CHECK (qty >= 0),
     PRIMARY KEY (product_id, size)
   );`
];

// Every table with the columns a dump holds, in the order its rows were added.
export const TABLES = {
  meta: { columns: ["key", "value"], order: "key" },
  settings: { columns: ["key", "value"], order: "seq" },
  products: { columns: ["id", "position", "data"], order: "seq" },
  orders: { columns: ["id", "number", "key", "created_at", "status", "name", "phone", "items", "totals", "extra"], order: "number" },
  deleted_orders: { columns: ["key", "number", "deleted_at"], order: "key" },
  counters: { columns: ["name", "value"], order: "name" },
  clients: { columns: ["id", "phone", "name", "created_at", "last_order_at", "hidden", "extra"], order: "seq" },
  chat_files: { columns: ["id", "name", "type", "size", "session", "text", "created_at", "time"], order: "seq" },
  stock: { columns: ["product_id", "size", "qty"], order: "seq" }
};
// stock came with a later SQLite schema, so a copy from before it may lack the table.
const OPTIONAL_TABLES = ["stock"];

export const DUMP_FORMAT = "zhuldyz-postgres";
// The application name the site connects with, so a restore can tell the site is still running.
export const SITE_APPLICATION = "zhuldyz-site";
const WRITE_LOCK = 20261029;
const INT8 = 20;
const RETRY_DELAY_MS = 1000;

export class DatabaseUnreachableError extends Error {}
export class NewDatabaseRefusedError extends Error {}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const quote = (name) => `"${name.replace(/"/g, '""')}"`;
// Counts and ms timestamps fit in a JS number; without this pg hands BIGINT back as a string.
const types = { getTypeParser: (oid, format) => (oid === INT8 ? Number : pg.types.getTypeParser(oid, format)) };

// PostgreSQL refuses the NUL character in text, which SQLite took: a visitor's name or a chat file's text with one
// would fail the whole write, and an order failing that way would go to the rescue file and then stop every start.
const cleanParams = (params) => params.map((value) => (typeof value === "string" ? value.replace(/\u0000/g, "") : value));

function runner(target) {
  const query = async (text, params = []) => (await target.query(text, cleanParams(params))).rows;
  return {
    query,
    one: async (text, params) => (await query(text, params))[0],
    run: async (text, params = []) => (await target.query(text, cleanParams(params))).rowCount
  };
}

function transactionRunner(client) {
  return {
    ...runner(client),
    // An error inside a PostgreSQL transaction cancels all of it; a part that may fail on its own runs in a savepoint.
    async savepoint(task) {
      await client.query("SAVEPOINT part");
      try {
        const result = await task();
        await client.query("RELEASE SAVEPOINT part");
        return result;
      } catch (error) {
        await client.query("ROLLBACK TO SAVEPOINT part");
        throw error;
      }
    }
  };
}

function wrap(pool) {
  async function session(begin, lock, task) {
    const client = await pool.connect();
    let broken;
    // pg reports a connection lost while the client is checked out as an "error" event, not only as a failed query;
    // the pool listens only while the client is idle, and an unheard event would stop the whole process.
    const lost = (error) => {
      broken = error;
    };
    client.on("error", lost);
    try {
      await client.query(begin);
      if (lock) await client.query("SELECT pg_advisory_xact_lock($1)", [WRITE_LOCK]);
      const result = await task(transactionRunner(client));
      await client.query("COMMIT");
      return result;
    } catch (error) {
      try {
        await client.query("ROLLBACK");
      } catch (undo) {
        broken = undo;
      }
      throw error;
    } finally {
      client.removeListener("error", lost);
      client.release(broken);
    }
  }
  let closing = null;
  return {
    ...runner(pool),
    // Writes run one at a time, as they did in SQLite: nothing a write has read can change before it commits.
    transaction: (task) => session("BEGIN", true, task),
    // Reads that must agree with each other (the catalog and its stock) all see one moment of the database.
    snapshot: (task) => session("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY", false, task),
    close: () => (closing ??= pool.end())
  };
}

function describeError(settings, error) {
  const where = `${settings.host}:${settings.port}`;
  if (error.code === "28P01") return `PostgreSQL at ${where} refused the password - check POSTGRES_PASSWORD in .env`;
  return `PostgreSQL at ${where} did not answer (${error.code || error.message}) - is Docker Desktop running? start-site.bat starts the database with "docker compose up -d postgres"`;
}

async function createDatabase(settings) {
  if (!/^[A-Za-z0-9_]{1,63}$/.test(settings.database)) throw new Error(`the database name "${settings.database}" may hold only Latin letters, digits and _`);
  const client = new pg.Client({ ...settings, database: "postgres" });
  try {
    await client.connect();
    await client.query(`CREATE DATABASE ${quote(settings.database)}`);
  } catch (error) {
    if (error.code !== "42P04") throw error;
  } finally {
    await client.end().catch(() => {});
  }
}

// Docker Desktop and the container may still be starting, so the first connection is tried until waitMs runs out.
// A database missing on the server is created; it is empty, and the migrations fill in the tables.
async function reach(settings, waitMs) {
  const deadline = Date.now() + waitMs;
  for (;;) {
    const client = new pg.Client({ ...settings, connectionTimeoutMillis: 5000 });
    try {
      await client.connect();
      return;
    } catch (error) {
      if (error.code === "3D000") {
        await createDatabase(settings);
        continue;
      }
      // SQL error codes are five characters; network errors (ECONNREFUSED, ENOTFOUND) and "the server is starting" are retried.
      const final = /^[0-9A-Z]{5}$/.test(error.code ?? "") && error.code !== "57P03";
      if (final || Date.now() >= deadline) throw new DatabaseUnreachableError(describeError(settings, error), { cause: error });
      await sleep(RETRY_DELAY_MS);
    } finally {
      await client.end().catch(() => {});
    }
  }
}

async function schemaVersion(db) {
  const table = await db.one("SELECT to_regclass('schema_version') IS NOT NULL AS present");
  if (!table.present) return 0;
  return (await db.one("SELECT COALESCE(MAX(version), 0) AS version FROM schema_version")).version;
}

// mayCreate is asked before the tables of a brand-new database are made: an empty database next to earlier data is an accident
// (a lost Docker volume, a wrong POSTGRES_DB), and order numbers from 1 would repeat numbers clients already have.
export async function openDatabase(settings, { waitMs = 0, mayCreate = () => true, application = SITE_APPLICATION, logger } = {}) {
  await reach(settings, waitMs);
  // Idle connections stay open, so a restore can tell a running site by its connections even after a quiet hour.
  // A transaction left hanging is cut off after a minute: while it holds the write lock no order could be saved.
  const pool = new pg.Pool({
    ...settings,
    application_name: application,
    max: 10,
    connectionTimeoutMillis: 10000,
    idleTimeoutMillis: 0,
    idle_in_transaction_session_timeout: 60000,
    keepAlive: true,
    types
  });
  pool.on("error", (error) => logger?.warn("a PostgreSQL connection broke, the next request opens a new one", { message: error.message }));
  const db = wrap(pool);
  try {
    const version = await schemaVersion(db);
    if (version > MIGRATIONS.length) throw new Error(`the database was made by a newer version of the site (schema ${version}, this one knows ${MIGRATIONS.length})`);
    if (version === 0 && !mayCreate()) throw new NewDatabaseRefusedError(`the PostgreSQL database "${settings.database}" is empty`);
    if (version < MIGRATIONS.length) {
      // Two starts at once wait for each other here, and the second finds the work done.
      await db.transaction(async (tx) => {
        await tx.run("CREATE TABLE IF NOT EXISTS schema_version (version INTEGER PRIMARY KEY)");
        for (let next = await schemaVersion(tx); next < MIGRATIONS.length; next += 1) {
          await tx.query(MIGRATIONS[next]);
          await tx.run("INSERT INTO schema_version (version) VALUES ($1)", [next + 1]);
        }
      });
    }
    return db;
  } catch (error) {
    await db.close();
    throw error;
  }
}

// The whole database as plain data: the daily copies, the copy outside the site folder and the zip download.
export function dumpDatabase(db) {
  return db.snapshot(async (tx) => {
    const tables = {};
    for (const [name, { columns, order }] of Object.entries(TABLES)) {
      tables[name] = await tx.query(`SELECT ${columns.map(quote).join(", ")} FROM ${name} ORDER BY ${order}`);
    }
    return { format: DUMP_FORMAT, schema: MIGRATIONS.length, createdAt: localIso(), tables };
  });
}

const isRecord = (value) => Boolean(value) && typeof value === "object" && !Array.isArray(value);

// Throws with the reason a value is not a dump of this site.
export function checkDump(dump) {
  if (!isRecord(dump) || dump.format !== DUMP_FORMAT || !isRecord(dump.tables)) throw new Error("it is not a database copy of this site");
  if (!(Number(dump.schema) <= MIGRATIONS.length)) throw new Error(`the copy was made by a newer version of the site (schema ${dump.schema})`);
  const missing = Object.keys(TABLES).filter((name) => !OPTIONAL_TABLES.includes(name) && !Array.isArray(dump.tables[name]));
  if (missing.length) throw new Error(`the copy has no ${missing.join(", ")} table`);
  for (const [name, rows] of Object.entries(dump.tables)) {
    if (Object.hasOwn(TABLES, name) && (!Array.isArray(rows) || !rows.every(isRecord))) throw new Error(`the ${name} table of the copy is damaged`);
  }
}

// Replaces everything in the database with the dump; meant to run inside db.transaction, so a failure changes nothing.
export async function loadDump(tx, dump) {
  checkDump(dump);
  await tx.run(`TRUNCATE ${Object.keys(TABLES).join(", ")}`);
  for (const [name, { columns }] of Object.entries(TABLES)) {
    const rows = dump.tables[name] ?? [];
    for (let start = 0; start < rows.length; start += 200) {
      const values = [];
      const groups = rows.slice(start, start + 200).map((row) => `(${columns.map((column) => `$${values.push(row[column] ?? null)}`).join(", ")})`);
      await tx.run(`INSERT INTO ${name} (${columns.map(quote).join(", ")}) VALUES ${groups.join(", ")}`, values);
    }
  }
}

// Fields the code does not know (added by hand or by an older version) ride along in "extra" instead of being dropped.
export function extraOf(record, known) {
  const extra = Object.fromEntries(Object.entries(record).filter(([field]) => !known.includes(field)));
  return Object.keys(extra).length ? JSON.stringify(extra) : null;
}

// A column damaged by a hand edit or a disk error reads as undefined, so one bad row cannot stop a whole list from loading.
export function parseColumn(text, valid) {
  try {
    const value = JSON.parse(text);
    return valid(value) ? value : undefined;
  } catch {
    return undefined;
  }
}

export const parseExtra = (text) => (text ? parseColumn(text, isRecord) : {});
